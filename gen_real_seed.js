// === Generate trains ===
const trains = [];
let trainId = 1;

function hashCode(s) { return s.split('').reduce((a,b)=>a+b.charCodeAt(0),0); }

for (const corridor of corridors) {
  const n = corridor.length;
  if (n < 2) continue;

  // Generate multiple train services per corridor
  // Express: only major stops
  // Normal: more stops
  // Stopping: all stops

  const hash = hashCode(corridor[0] + corridor[corridor.length-1]);
  let numTrains = 5 + (hash % 4); // 5-8 trains per corridor
  // Add sub-segments
  const allRoutes = [corridor];
  for (let seg = 0; seg < 3; seg++) {
    if (n > 4 + seg) {
      const a = seg, b = n - 1 - seg;
      if (a < b) allRoutes.push(corridor.slice(a, b + 1));
    }
  }
  // Reverse
  allRoutes.push([...corridor].reverse());

  for (const route of allRoutes) {
    if (trains.length >= 1000) break;
    const rn = route.length;
    const rhash = hashCode(route[0] + route[rn-1]);

    for (let t = 0; t < numTrains && trains.length < 1000; t++) {

    const stops = []; // station names

    if (t === 0) {
      // Express: first, a few key stops, last
      const keyIndices = [0];
      const step = Math.max(1, Math.floor(rn / (2 + (rhash % 3))));
      for (let i = step; i < rn - 1; i += step) keyIndices.push(i);
      keyIndices.push(rn - 1);
      const unique = [...new Set(keyIndices)].sort((a,b)=>a-b);
      for (const i of unique) stops.push(route[i]);
    } else if (t === 1) {
      // Normal: skip some small stops
      const skipSet = new Set();
      for (let i = 1; i < rn - 1; i++) {
        if ((i + rhash) % 3 === 0) skipSet.add(i);
      }
      for (let i = 0; i < rn; i++) {
        if (!skipSet.has(i)) stops.push(route[i]);
      }
    } else {
      // All stops
      for (const s of route) stops.push(s);
    }

    if (stops.length < 2) continue;

    const code = 'G' + trainId;
    trainId++;

    // Carriage config
    const businessCars = 1;
    const firstCars = 1 + (rhash % 2);
    const secondCars = 5 + (rhash % 4);

    // Departure time (6:00-20:00)
    const baseHour = 6 + ((rhash + t * 13) % 14);
    const baseMin = ((rhash * 7 + t * 17) % 60);

    trains.push({
      code, line: 'L' + code.substring(1),
      businessCars, firstCars, secondCars,
      stops: stops.map((sname, idx) => {
        const totalMin = baseMin + idx * (25 + (rhash % 25));
        const h = (baseHour + Math.floor(totalMin / 60)) % 24;
        const m = totalMin % 60;
        const time = `${String(h).padStart(2,'0')}:${String(m).padStart(2,'0')}`;
        const isFirst = idx === 0, isLast = idx === stops.length - 1;
        return {
          name: sname,
          index: idx + 1,
          inTime: isFirst ? null : time,
          outTime: isLast ? null : `${String((h + Math.floor((m+3)/60)) % 24).padStart(2,'0')}:${String((m+3) % 60).padStart(2,'0')}`,
          mileage: idx * 70 + (rhash % 50),
        };
      }),
    });
    }
  }
}

